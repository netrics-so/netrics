import { randomUUID } from "node:crypto";

import type { CustomApiAuth } from "@netrics/connector-sdk/custom-api";

import {
  decryptCredentials,
  encryptCredentials,
  type CredentialBinding,
  type CredentialKeyring,
} from "../../credentials.js";
import { Secret } from "../../secret.js";
import { oauthRedirectUri, type ConfiguredOAuthProvider } from "../config.js";

// Custom OAuth (milestone 13, #805, ADR 0027): the OAuth app of a custom API
// is the user's, not the instance's. Its endpoints are connection data (the
// connection's definition, pinned or draft), its client ID and secret live in
// the connection's credential envelope next to the refresh token, and the
// account id is generated by netrics: a custom provider has no OpenID
// account endpoint in general. Every custom grant has its own account, so
// the ADR 0012 shared-grant rules never find another holder.

export const CUSTOM_OAUTH_PROVIDER_ID = "custom";

/** The custom OAuth envelope in connections.credentials_encrypted. */
export interface CustomOAuthCredentials {
  /** The environment host the envelope is bound to (C-G3). */
  host: string;
  clientId: string;
  clientSecret: string;
  /** Authorization code only; null before the first grant or without one. */
  refreshToken: string | null;
}

export function sealCustomOAuthCredentials(
  value: CustomOAuthCredentials,
  keyring: CredentialKeyring,
  binding: CredentialBinding,
): Buffer {
  const envelope: CustomOAuthCredentials = {
    host: value.host,
    clientId: value.clientId,
    clientSecret: value.clientSecret,
    refreshToken: value.refreshToken,
  };
  return Buffer.from(
    encryptCredentials(JSON.stringify(envelope), keyring, binding),
    "utf8",
  );
}

/** Opens a custom OAuth envelope; throws when it does not have that shape. */
export function openCustomOAuthCredentials(
  sealed: Buffer,
  keyring: CredentialKeyring,
  binding: CredentialBinding,
): CustomOAuthCredentials {
  const parsed = JSON.parse(
    decryptCredentials(sealed.toString("utf8"), keyring, binding),
  ) as Partial<CustomOAuthCredentials>;
  if (
    typeof parsed.host !== "string" ||
    typeof parsed.clientId !== "string" ||
    !parsed.clientId ||
    typeof parsed.clientSecret !== "string" ||
    !parsed.clientSecret
  ) {
    throw new Error("custom oauth envelope is incomplete");
  }
  return {
    host: parsed.host,
    clientId: parsed.clientId,
    clientSecret: parsed.clientSecret,
    refreshToken:
      typeof parsed.refreshToken === "string" && parsed.refreshToken
        ? parsed.refreshToken
        : null,
  };
}

export interface CustomOAuthProvider extends ConfiguredOAuthProvider {
  grant: "authorization_code" | "client_credentials";
  /** The definition's scopes (maybe none). */
  scopes: readonly string[];
}

export type CustomOAuthAuth = Extract<
  CustomApiAuth,
  { type: "oauth_client_credentials" | "oauth_authorization_code" }
>;

export function isCustomOAuthAuth(
  auth: Pick<CustomApiAuth, "type">,
): auth is CustomOAuthAuth {
  return (
    auth.type === "oauth_client_credentials" ||
    auth.type === "oauth_authorization_code"
  );
}

function hostname(url: string): string {
  return new URL(url).hostname.replace(/^\[|\]$/g, "");
}

/**
 * The provider of a custom OAuth connection: endpoints from its definition
 * (pinned or draft), client ID and secret from its envelope, PKCE S256
 * unless the definition turns it off, no OpenID, the token and revoke hosts
 * as server domains. Throws when the auth type is not OAuth.
 */
export function customOAuthProvider(
  definition: { name?: string; auth: CustomApiAuth },
  credentials: Pick<CustomOAuthCredentials, "clientId" | "clientSecret">,
  webOrigin: string,
): CustomOAuthProvider {
  const auth = definition.auth;
  if (!isCustomOAuthAuth(auth)) {
    throw new Error("the definition does not use OAuth");
  }
  const code = auth.type === "oauth_authorization_code" ? auth : null;
  const revocationEndpoint = code?.revokeUrl ?? null;
  const serverDomains = [
    ...new Set(
      [auth.tokenUrl, ...(revocationEndpoint ? [revocationEndpoint] : [])].map(
        hostname,
      ),
    ),
  ];
  return {
    definition: {
      id: CUSTOM_OAUTH_PROVIDER_ID,
      name: definition.name || "Custom API",
      authorizationEndpoint: code?.authorizeUrl ?? auth.tokenUrl,
      tokenEndpoint: auth.tokenUrl,
      revocationEndpoint,
      pkce: code ? (code.pkce ? "S256" : null) : null,
      openIdConnect: null,
      identityScopes: [],
      authorizationParams: code?.authorizeParams ?? {},
      serverDomains,
      accountPermissionsUrl: new URL(code?.authorizeUrl ?? auth.tokenUrl)
        .origin,
    },
    clientId: credentials.clientId,
    clientSecret: new Secret(credentials.clientSecret),
    redirectUri: oauthRedirectUri(webOrigin, CUSTOM_OAUTH_PROVIDER_ID),
    clientAuth: auth.clientAuth,
    grant: code ? "authorization_code" : "client_credentials",
    scopes: [...auth.scopes],
  };
}

/** The account id of a custom grant: netrics-generated, unique per grant. */
export function generateCustomAccountSub(): string {
  return `${CUSTOM_OAUTH_PROVIDER_ID}:${randomUUID()}`;
}
